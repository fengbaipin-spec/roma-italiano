// a preposition joined with an article: del, dello, della, dell', dei, degli, delle, and the same for a, da, in, su
const PREPS = [["di", "de", "……的（也表示“一些”，如 del pane）"], ["a", "a", "在；到；给"], ["da", "da", "从；在某人那里"],
  ["in", "ne", "在……里"], ["su", "su", "在……上"]];
const ARTS = [["il", "l"], ["lo", "llo"], ["la", "lla"], ["l'", "ll'"], ["i", "i"], ["gli", "gli"], ["le", "lle"]];
for (const [prep, stem, meaning] of PREPS) {
  for (const [art, end] of ARTS) G[stem + end] = ["介词 + 冠词", `${prep} + ${art}：${meaning}`];
}

export const GLOSS = G;

